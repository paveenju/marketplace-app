-- Initial schema for the marketplace database.
--
-- This file is the source of truth for the schema: EF Core maps onto what is
-- created here, it does not generate it. Once merged, never edit this script -
-- DbUp journals it as applied and will not re-run it. Add a new NNN_*.sql file
-- instead.

CREATE TABLE categories (
    id          integer GENERATED BY DEFAULT AS IDENTITY
                CONSTRAINT pk_categories PRIMARY KEY,
    name        text NOT NULL,
    description text NULL
);

-- Category names are the user-facing identifier, so they must be unique.
CREATE UNIQUE INDEX ix_categories_name ON categories (name);

CREATE TABLE products (
    id          integer GENERATED BY DEFAULT AS IDENTITY
                CONSTRAINT pk_products PRIMARY KEY,
    name        text NOT NULL,
    description text NULL,
    price       numeric(10, 2) NOT NULL,
    stock       integer NOT NULL,
    image_url   text NULL,
    created_at  timestamp with time zone NOT NULL,
    category_id integer NOT NULL
                CONSTRAINT fk_products_categories REFERENCES categories (id)
                ON DELETE RESTRICT -- don't allow deleting a category that still has products
);

CREATE INDEX ix_products_category_id ON products (category_id);
